"""
Build the negative-video false-alarm tables for the paper from the SAFERFIRE
negative-video runs (results/negative_videos/saferfire_false_alarms.xlsx, 1 run
per video and configuration; 1 = false alarm, 0 = no alarm).

Outputs (paper/tables/):
    falsealarm_neg_summary.tex     main text (tab:falsealarm): number (%) of the
                                   69 negative videos with a false alarm, per
                                   configuration of Light Only, Two-Step and Best Only
    falsealarm_neg_per_video.tex   Appendix A (tab:falsealarm_per_video): which
                                   videos (N#, as in tab:all_videos) raised the alarm

Video IDs N1-N69 follow data/negative_videos.csv.
"""

import csv
from pathlib import Path

from method_comparison import METHODS, load

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
TABLES = REPO / "paper" / "tables"
MANIFEST = REPO / "data" / "negative_videos.csv"

CONFS = [0.125, 0.25, 0.50, 0.75]
RULES = [(1, 1), (3, 2), (5, 3)]


def c(x):
    return f"{x:g}"


def cshow(x):
    return "0.125" if x == 0.125 else f"{x:.2f}"


def load_neg():
    sf = next(m for m in METHODS if m["method"] == "SAFERFIRE")
    d = load(sf["neg"], sf["label"], "neg")
    with open(MANIFEST, newline="", encoding="utf-8") as f:
        ids = {r["file"].removesuffix(".mp4"): int(r["id"]) for r in csv.DictReader(f)}
    unknown = set(d["video"]) - set(ids)
    if unknown:
        raise ValueError(f"videos not in MANIFEST.csv: {sorted(unknown)}")
    d["vid"] = d["video"].map(ids)
    n_videos = d["vid"].nunique()
    # {(approach, config): sorted N# with a false alarm}
    alarms = {k: sorted(g.loc[g["value"] == 1, "vid"]) for k, g in d.groupby(["approach", "config"])}
    return alarms, n_videos


def key_light(cl, rule):
    return ("Light Only", f"c={c(cl)} ({rule[0]},{rule[1]})")


def key_best(ch):
    return ("Best Only", f"c={c(ch)}")


def key_two(cl, ch, rule):
    return ("Two-Step", f"cL={c(cl)} cH={c(ch)} ({rule[0]},{rule[1]})")


# ------------------------------------------------------------------
# Main-text table: count (%) per configuration
# ------------------------------------------------------------------

def cell(alarms, key, n):
    if key not in alarms:
        return ""
    k = len(alarms[key])
    return f"{k} ({100 * k / n:.1f})"


def summary_table(alarms, n):
    lines = [
        "% Generated by analysis/false_alarm_tables.py -- do not edit by hand.",
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption[False alarms on the negative videos.]{\hl{False alarms on the "
        rf"{n} negative videos for every evaluated configuration of the Light Only, Two-Step and Best Only approaches "
        r"(one run per video): number of videos in which an alarm was raised and, in parentheses, percentage of the videos. "
        r"Two-Step was evaluated only with $c_H \geq c_L$ (empty cells); Best Only depends only on $c_H$. "
        r"The videos responsible for each value are listed in Table}~\ref{tab:falsealarm_per_video}\hl{.}}",
        r"\label{tab:falsealarm}",
        r"\setlength{\tabcolsep}{7pt}",
        r"\begin{tabular}{cc@{\hspace{14pt}}c@{\hspace{14pt}}cccc}",
        r"\toprule",
        r" & & & \multicolumn{4}{c}{\textbf{Two-Step}, $c_H$} \\",
        r"\cmidrule(lr){4-7}",
        r"$c_L$ & $(W,T)$ & \textbf{Light Only} & 0.125 & 0.25 & 0.50 & 0.75 \\",
        r"\midrule",
    ]
    for i, cl in enumerate(CONFS):
        if i:
            lines.append(r"\addlinespace[4pt]")
        for j, rule in enumerate(RULES):
            cells = [cshow(cl) if j == 0 else "", f"({rule[0]},{rule[1]})", cell(alarms, key_light(cl, rule), n)]
            cells += [cell(alarms, key_two(cl, ch, rule), n) if ch >= cl else "" for ch in CONFS]
            lines.append(" & ".join(cells) + r" \\")
    lines += [
        r"\midrule",
        r"\multicolumn{3}{l}{\textbf{Best Only}, $c_H$ as in the column} & "
        + " & ".join(cell(alarms, key_best(ch), n) for ch in CONFS) + r" \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------
# Appendix table: videos with a false alarm per configuration
# ------------------------------------------------------------------

def per_video_table(alarms, n):
    rows = [("Light Only", cshow(cl), "", f"({w},{t})", key_light(cl, (w, t))) for cl in CONFS for (w, t) in RULES]
    rows += [("Best Only", "", cshow(ch), "", key_best(ch)) for ch in CONFS]
    rows += [("Two-Step", cshow(cl), cshow(ch), f"({w},{t})", key_two(cl, ch, (w, t)))
             for cl in CONFS for ch in CONFS if ch >= cl for (w, t) in RULES]

    ever = sorted({v for vids in alarms.values() for v in vids})
    never = n - len(ever)
    head = r"Approach & $c_L$ & $c_H$ & $(W,T)$ & \makecell{False\\alarms} & Negative videos with a false alarm \\"
    lines = [
        "% Generated by analysis/false_alarm_tables.py -- do not edit by hand.",
        r"\begingroup",
        r"\footnotesize",
        r"\renewcommand{\baselinestretch}{1}\selectfont   % single spacing in the table (review mode doubles it)",
        r"\setlength{\tabcolsep}{4pt}",
        r"\setlength{\LTcapwidth}{\textwidth}",
        r"\begin{longtable}{lcccc>{\raggedright\arraybackslash}p{8.4cm}}",
        r"\caption[Negative videos with a false alarm in each configuration.]"
        rf"{{\hl{{Negative videos (identifiers N1--N{n} as in Table}}~\ref{{tab:all_videos}}\hl{{) in which each "
        rf"configuration raised a false alarm (one run per video). {len(ever)} of the {n} videos raised a false alarm in at least "
        rf"one configuration; the remaining {never} never did.}}}}",
        r"\label{tab:falsealarm_per_video}\\",
        r"\toprule", head, r"\midrule", r"\endfirsthead",
        rf"\multicolumn{{6}}{{l}}{{\footnotesize\itshape Table~\ref{{tab:falsealarm_per_video}} (continued)}}\\",
        r"\toprule", head, r"\midrule", r"\endhead",
        r"\midrule", r"\multicolumn{6}{r}{\footnotesize\itshape continued on next page}\\", r"\endfoot",
        r"\bottomrule", r"\endlastfoot",
    ]
    prev = None
    for appr, cl, ch, rule, key in rows:
        if prev is not None and appr != prev:
            lines.append(r"\midrule")
        vids = alarms.get(key)
        lst = ", ".join(f"N{v}" for v in vids) if vids else ("--" if vids is None else "none")
        cnt = str(len(vids)) if vids is not None else "--"
        lines.append(" & ".join([appr if appr != prev else "", cl, ch, rule, cnt, lst]) + r" \\")
        prev = appr
    lines += [r"\end{longtable}", r"\endgroup", ""]
    return "\n".join(lines)


def main():
    alarms, n = load_neg()
    (TABLES / "falsealarm_neg_summary.tex").write_text(summary_table(alarms, n), encoding="utf-8")
    (TABLES / "falsealarm_neg_per_video.tex").write_text(per_video_table(alarms, n), encoding="utf-8")
    print(f"wrote falsealarm_neg_summary.tex and falsealarm_neg_per_video.tex ({len(alarms)} configurations, {n} videos)")


if __name__ == "__main__":
    main()
